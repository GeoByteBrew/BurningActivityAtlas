"""Step 0 — data exploration report (data sufficiency for calibration).

Answers: how many detections per sensor/platform/year, how sparse are 1 km / 5 km cell-days,
how many near-simultaneous MODIS–VIIRS overpass pairs exist, and how pixel size varies with scan.

The report loads the detections of the tiles it covers in memory. A regional run covers every
tile; a world run covers the busiest tiles only (--max-tiles, default 6) or those given with
--tiles, which is enough to judge data sufficiency.

Output: outputs/reports/step0_data_exploration.md (+ CSV tables in outputs/csv, figures in outputs/figures)
"""
import _bootstrap  # noqa: F401

from datetime import date

import geopandas as gpd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from mvh import store
from mvh.config import cli, load_config, path, record_start, setup_logging
from mvh.grid import label
from mvh.temporal import assign_overpasses, match_overpasses, matched_cell_counts

log = setup_logging("05_report")

# Below this many cell-overpasses with both sensors positive, the matched-pair ratio is too noisy to read.
MIN_PAIRS_BOTH = 300


from mvh.report import md_table  # noqa: E402


def main():
    ap = cli(__doc__)
    ap.add_argument("--max-tiles", type=int, default=6)
    args = ap.parse_args()
    cfg = load_config(args.config)
    agg, grids = path(cfg, "aggregated"), path(cfg, "grids")
    rep, fig, csv = path(cfg, "reports"), path(cfg, "figures"), path(cfg, "csv")
    main_q = cfg["qc"]["main_scenario"]
    scen = list(cfg["qc"]["scenarios"])
    droot = path(cfg, "processed") / "detections"
    all_tiles = store.tiles(agg / "cells")
    tiles = store.select(all_tiles, args.tiles)
    if not args.tiles and len(tiles) > args.max_tiles:
        size = {t: store.read(agg / "cells", t, columns=["n"])["n"].sum() for t in tiles}
        tiles = sorted(tiles, key=size.get, reverse=True)[: args.max_tiles]
    partial = len(tiles) < len(all_tiles)
    log.info("report on %d of %d tiles: %s", len(tiles), len(all_tiles), tiles)

    frames = []
    for t in tiles:
        for y in store.years(droot, t):
            d = store.read(droot, t, y)
            d = d[d["f_base_ok"]]
            if len(d):
                frames.append(assign_overpasses(d.assign(region=d["region"].astype(object)),
                                                cfg["temporal"]["overpass_gap_min"], prefix=f"{t}_"))
    det = pd.concat(frames, ignore_index=True)
    ov = pd.concat([store.read_tile(agg / "overpasses", t) for t in tiles], ignore_index=True)
    det["year"] = det["acq_datetime"].dt.year
    det["month"] = det["acq_datetime"].dt.month
    dq = det[det[f"q_{main_q}"]]
    n_days = (date.fromisoformat(cfg["period"]["end"]) - date.fromisoformat(record_start(cfg))).days + 1

    sections = [
        f"# Step 0 — Data exploration report ({cfg['aoi']['name']})",
        (f"**Partial report: {len(tiles)} busiest of {len(all_tiles)} processing tiles** ({', '.join(tiles)})." if partial else ""),
        f"Period: {record_start(cfg)} – {cfg['period']['end']} ({n_days} days) · Main quality scenario: **{main_q}** · "
        f"Generated by: `scripts/05_explore_report.py`",
    ]

    # 1. Coverage per source
    cov = det.groupby(["sensor", "platform", "source"]).agg(
        first=("acq_datetime", "min"), last=("acq_datetime", "max"), n=("det_id", "size"),
        days_with_det=("acq_date_utc", "nunique")).reset_index()
    cov["first"], cov["last"] = cov["first"].dt.date.astype(str), cov["last"].dt.date.astype(str)
    sections += ["## 1. Source coverage (after basic QC)", md_table(cov)]

    # 1b. Per sub-region
    reg = det[det[f"q_{main_q}"]].pivot_table(index="region", columns="platform", values="det_id",
                                               aggfunc="size", fill_value=0).reset_index()
    sections += [f"## 1b. Detections per sub-region ({main_q}, whole period)", md_table(reg)]

    # 2. QC scenarios
    sc = det.groupby(["sensor", "platform"])[[f"q_{s}" for s in scen]].sum().reset_index()
    sc.columns = ["sensor", "platform"] + scen
    sections += ["## 2. Effect of the quality scenarios (number of detections)", md_table(sc)]
    sc.to_csv(csv / "step0_qc_scenarios.csv", index=False)

    # 3. Annual counts
    yr = dq.pivot_table(index="year", columns="platform", values="det_id", aggfunc="size", fill_value=0)
    yr.to_csv(csv / "step0_annual_counts.csv")
    sections += [f"## 3. Annual detections ({main_q})", md_table(yr.reset_index())]
    ax = yr.plot(marker="o", figsize=(9, 4), title=f"Annual detections — {main_q}")
    ax.set_ylabel("detections"); plt.tight_layout(); plt.savefig(fig / "step0_annual.png", dpi=130); plt.close()

    mo = dq.groupby(["platform", "year", "month"]).size().groupby(["platform", "month"]).mean().unstack(0).fillna(0)
    ax = mo.plot(kind="bar", figsize=(9, 4), title="Mean monthly detections (average over years)")
    ax.set_ylabel("detections / month"); plt.tight_layout(); plt.savefig(fig / "step0_monthly.png", dpi=130); plt.close()
    sections += ["![annual](../figures/step0_annual.png)", "![monthly](../figures/step0_monthly.png)"]

    # 4. Pixel size (scan × track) — MODIS growth off-nadir
    px = dq.groupby("platform")["pixel_area_km2"].describe(percentiles=[.5, .9]).reset_index()
    px = px[["platform", "count", "mean", "50%", "90%", "max"]]
    sections += ["## 4. Pixel area (scan × track, km²)",
                 "MODIS pixels grow to ~10 km² towards the scan edge, so MODIS location uncertainty on a 1 km grid is high.",
                 md_table(px)]

    # 5. Day / night
    dn = dq.pivot_table(index="platform", columns="daynight", values="det_id", aggfunc="size", fill_value=0).reset_index()
    sections += ["## 5. Day / night split", md_table(dn)]

    # 6. Sparsity per scale
    rows = []
    for s in cfg["grid"]["sizes_m"]:
        lab = label(s)
        gf = grids / f"grid_{lab}.gpkg"
        if gf.exists() and not partial:
            n_cells = int(gpd.read_file(gf, ignore_geometry=True)["in_aoi"].sum())
        else:  # not materialized: all cells of the tiles covered (upper bound, sea included)
            n_cells = int(len(tiles) * (cfg["grid"]["tile_cells"] * cfg["harmonization"]["factor_scale_m"] / s) ** 2)
        d = pd.concat([store.read_tile(agg / f"daily_{lab}_{main_q}", t, columns=["platform", "n_det"]) for t in tiles])
        for p, sub in d.groupby("platform"):
            rows.append({"scale": lab, "platform": p, "cells_in_aoi": n_cells,
                         "nonempty_cell_days": len(sub),
                         "share_nonempty_%": 100 * len(sub) / (n_cells * n_days),
                         "mean_det_if_nonempty": float(sub["n_det"].mean()),
                         "max_det": int(sub["n_det"].max())})
    sp = pd.DataFrame(rows)
    sp.to_csv(csv / "step0_sparsity.csv", index=False)
    sections += ["## 6. Sparsity: non-empty cell-days", md_table(sp)]

    # 7. Near-simultaneous overpass pairs
    rows = []
    dq_ov = dq  # detections of the main scenario, overpass ids from all clean detections
    for a, b in cfg["temporal"]["match_pairs"]:
        for tol in cfg["temporal"]["match_tolerance_min"]:
            pairs = match_overpasses(ov, a, b, tol)
            for s in cfg["grid"]["sizes_m"]:
                lab = label(s)
                m = matched_cell_counts(dq_ov, pairs, f"cell_{lab}")
                both = m[(m.n_a > 0) & (m.n_b > 0)]
                rho = m[["n_a", "n_b"]].corr(method="spearman").iat[0, 1] if len(m) > 2 else float("nan")
                rows.append({"pair": f"{a}–{b}", "tol_min": tol, "scale": lab,
                             "matched_overpasses": len(pairs),
                             "cells_union": len(m), "both>0": len(both),
                             "only_MODIS": int(((m.n_a > 0) & (m.n_b == 0)).sum()),
                             "only_VIIRS": int(((m.n_a == 0) & (m.n_b > 0)).sum()),
                             "spearman": rho,
                             "ratio_VIIRS/MODIS": m.n_b.sum() / m.n_a.sum() if m.n_a.sum() else float("nan")})
    mt = pd.DataFrame(rows)
    mt.to_csv(csv / "step0_overpass_matching.csv", index=False)
    sections += ["## 7. Near-simultaneous overpass matching (core calibration data)",
                 "Note: only overpasses with ≥1 detection are visible; cells where neither sensor detected anything are not in the table.",
                 md_table(mt)]

    # 8. Automatic verdict
    key = mt[(mt["pair"] == "Aqua–S-NPP") & (mt["tol_min"] == min(cfg["temporal"]["match_tolerance_min"]))]
    verdict = ["## 8. Is the overpass-level diagnostic usable?"]
    for _, r in key.iterrows():
        ok = r["both>0"] >= MIN_PAIRS_BOTH
        verdict.append(f"- **{r['scale']}**, Aqua–S-NPP ±{r['tol_min']} min: both sensors positive in {r['both>0']:,} cell-overpasses → "
                       + ("enough pairs to read the overpass-level sensor ratio." if ok else
                          f"below {MIN_PAIRS_BOTH} pairs → the overpass-level ratio at this scale is noisy; rely on the daily factors of stage 06."))
    sections += verdict

    report = rep / "step0_data_exploration.md"
    report.write_text("\n\n".join(x for x in sections if x) + "\n", encoding="utf-8")
    log.info("report written: %s", report)


if __name__ == "__main__":
    main()
